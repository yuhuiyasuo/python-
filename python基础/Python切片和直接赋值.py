a = [1,2,3]
b = a     #直接赋值是共享一个对象
c = a[:]  #切片操作是创建一个新对象并复制内容，切片只拷贝外层。

print(id(a) == id(b))    #True
print(id(a) == id(c))    #False

a = [1, [2,3], 4]
c = a[:]       # 切片浅拷贝  浅拷贝拷贝引用，深拷贝创建新对象
a[1].append(5) # 修改内层列表
print(c)       # [1, [2,3,5], 4] → 内层仍同步变化

t = (1,2,3)
m = t[:]


print(id(t) == id(m))    #True   元组是不可变的对象

