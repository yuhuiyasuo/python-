# Python x += 1 和 x = x + 1 完整区别
# 核心结论先行
# 对于不可变对象（int/str/tuple）：效果几乎一样，但执行机制略有差别；
# 对于可变对象（list）：完全不是一回事！行为差异巨大；
# 语法层面：+= 是原地增强赋值运算符，对应魔法方法 __iadd__；
# x = x + 1 是普通二元运算 + 重新赋值，调用 __add__。

a = [1,2]
b = a
a += [3]
print(a,b) # [1,2,3] [1,2,3]  原地修改，b跟着变

a = [1,2]
b = a
a = a + [3]
print(a,b) # [1,2,3] [1,2]   a指向新列表，b不变



# 三、魔法方法底层原理
# x = x + y
# 调用 x.__add__(y)，返回新对象，然后变量重新绑定。
# x += y
# 优先调用 x.__iadd__(y)：
# 如果对象实现 __iadd__：原地修改自身，返回自己；
# 如果没有实现（int、str）：回退执行 x = x + y。